import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { compileSnapshots, primarySchedule, scheduleWindowsFor } from '../src/lib/roadmap-projection.mjs';
import { releaseSchema, changeSchema, eventSchema } from '../src/lib/roadmap-content-schema.mjs';
function exercise(check){
 const work={id:"W-01",program:"P-01",phase:"development",delivery:{state:"unassigned"},schedule:{start:"2026-11-16",end:"2026-11-16",kind:"observed"},updatedAt:"2026-11-16"};
 const release={id:"R-01",program:"P-01",displayName:{zh:"示例",en:"Example"},summary:{zh:"说明",en:"Summary"},version:null,date:"2026-11-20",preview:false,changeIds:["C-01"],publicUpdatedAt:"2026-11-27"};
 const change={id:"C-01",releaseId:"R-01",implementation:"implemented",verification:"pass",workIds:["W-01"],publicUpdatedAt:"2026-11-27"};
 const event={id:"E-01",program:"P-01",date:"2026-11-20",kind:"release",releaseId:"R-01",publicUpdatedAt:"2026-11-27"};
 const store={program:[{id:"P-01"}],work:[work],event:[event],relation:[],release:[release],change:[change]};
 const [v1,v2]=compileSnapshots(store,JSON.stringify);
 check("legacy observed remains observed",v2.workItems[0].scheduleWindows[0].kind==="observed");
 check("v1 work preserved",JSON.stringify(v1.workItems[0])===JSON.stringify(work));
 check("release v1 compatibility",v1.events[0].kind==="milestone"&&!Object.hasOwn(v1.events[0],"releaseId"));
 check("same release derived summary",v2.events[0].description===release.summary&&v2.events[0].releaseId===release.id);
 check("nullable version",v2.releases[0].version===null);
 check("actual revision date",v2.publicUpdatedAt==="2026-11-27"&&v1.updatedAt==="2026-11-20");
 check("deterministic projection",JSON.stringify(compileSnapshots(store,JSON.stringify))===JSON.stringify([v1,v2]));
 check("actual before observed",primarySchedule({...work,scheduleWindows:[...scheduleWindowsFor(work),{id:"W-A",kind:"actual",start:"2026-11-20",end:"2026-11-25",commitment:"none"}]}).kind==="actual");
 check("partial window no duration",primarySchedule({...work,scheduleWindows:[{id:"W-A",kind:"actual",start:"2026-11-20",end:null,commitment:"none"}]})===null);
 const rejects=(s)=>{try{compileSnapshots(s,JSON.stringify);return false;}catch{return true;}};
 check("unknown release reference",rejects({...store,event:[{...event,releaseId:"R-02"}]}));
 check("preview cannot emit release event",rejects({...store,release:[{...release,preview:true,date:null}]}));
 check("missing change",rejects({...store,change:[]}));
 check("planned cannot be verified implementation",rejects({...store,change:[{...change,implementation:"planned"}]}));
 check("duplicate release event",rejects({...store,event:[event,{...event,id:"E-02"}]}));
 check("future remains undated",rejects({...store,work:[{...work,phase:"future"}]}));
 check("invalid date range",rejects({...store,work:[{...work,schedule:{...work.schedule,end:"2026-11-15"}}]}));
 check("non-plan commitment rejected",rejects({...store,work:[{...work,scheduleWindows:[{id:"W-A",kind:"forecast",start:null,end:null,commitment:"committed"}]}]}));
 check("no accidental release from work",compileSnapshots({...store,event:[],release:[],change:[]},JSON.stringify)[1].releases.length===0);
}
exercise((name,pass)=>assert.equal(pass,true,name));
const v1=JSON.parse(readFileSync('src/data/roadmap.generated.json','utf8')),v2=JSON.parse(readFileSync('src/data/roadmap.v2.generated.json','utf8'));
assert.equal(v2.schemaVersion,2);
assert.deepEqual(v2.workItems.map(w=>w.id),v1.workItems.map(w=>w.id));
assert.deepEqual(v2.events.map(e=>e.id),v1.events.map(e=>e.id));
assert(v2.releases.every(r=>releaseSchema.safeParse(r).success));
assert(v2.changes.every(c=>changeSchema.safeParse(c).success));
assert(!releaseSchema.safeParse({id:'BAD',privateRevision:'hidden'}).success);
assert(!eventSchema.safeParse({kind:'release',releaseId:'MISSING'}).success);
console.log('Roadmap v2 projection: PASS');
